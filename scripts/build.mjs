import { readFileSync, writeFileSync } from 'node:fs'

const read = (file) => readFileSync(new URL('../' + file, import.meta.url), 'utf8').replace(/\r\n/g, '\n')
const write = (file, content) => writeFileSync(new URL('../' + file, import.meta.url), content)

function panel(channel) {
  const source = read('channels/' + channel + '/client/client.js')
  const begin = '  factory: (require) => {'
  const start = source.indexOf(begin)
  const end = source.lastIndexOf('\n  },\n})')
  if (start < 0 || end < start) throw new Error('无法读取 ' + channel + ' 面板入口')
  return '((require) => {' + source.slice(start + begin.length, end) + '\n  })(require)'
}

function presets(channel) {
  const source = read('channels/' + channel + '/cordis.patch.yml')
  const lines = source.split('\n')
  const start = lines.indexOf('- insert:')
  if (start < 0 || !lines[start + 3]?.startsWith('    - id: preset-')) throw new Error('无法读取 ' + channel + ' 的预设')
  return lines.slice(start + 3).join('\n').trimEnd()
}

write('client/client.js', [
  '// Generated by scripts/build.mjs',
  "window.__ModuleLoader__.load({ id: 'dsh-aurabot-unified', factory: (require) => {",
  '  const qq = ' + panel('qq'),
  '  const wechat = ' + panel('wechat'),
  read('client/shell.js'),
  '  return createUnifiedPanel(require, { qq, wechat })',
  '} })',
  '',
].join('\n'))

write('cordis.patch.yml', [
  '- insert:',
  '    - id: aurabot-unified',
  '      name: dsh-aurabot-unified',
  presets('qq'),
  presets('wechat'),
  '',
].join('\n'))
